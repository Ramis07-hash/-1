# Создаем переменные разных типов данных
name = "Ramis"        # строка (str)
age = 18            # целое число (int)
height = 1.75         # дробное число (float)
is_student = True     # логическое значение (bool)

# Выводим переменные на экран
print(name)
print(age)
print(height)
print(is_student)





# Создаем две переменные
a = 10
b = 7

# Выводим результаты сравнений
print("Больше:", a > b)
print("Меньше:", a < b)
print("Равно:", a == b)
print("Не равно:", a != b)






